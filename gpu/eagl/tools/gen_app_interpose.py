"""Generate app_interpose.c for libheroapp (E-0356): dyld interposing tuples that send every OpenGLES.framework C entry point an application calls to the
EAGL bridge's export of the same name (lib/libheroeagl-app.dylib, bound by app_gl_bind() once it is loaded), or on to the system's own while it is not.
The names come from the SDK's OpenGLES.tbd, as in gen_gl_stubs.py.  gen_app_interpose.py [TBD] > src/app_interpose.c"""
import re, subprocess, sys
tbd = sys.argv[1] if len(sys.argv) > 1 else subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip() + '/System/Library/Frameworks/OpenGLES.framework/OpenGLES.tbd'
syms = sorted(set(re.findall(r'\b_(gl[A-Za-z0-9_]+)\b', open(tbd).read())))
o = []; w = o.append
w('// GENERATED by tools/gen_app_interpose.py: do not edit.')
w('#include <dlfcn.h>')
w('#define N %d' % len(syms))
w('#if __has_feature(ptrauth_calls)')
w('#define BR "braaz x16"')
w('#else')
w('#define BR "br x16"')
w('#endif')
w('__attribute__((visibility("hidden"), used)) void *app_tab[N + 1];')
w('__attribute__((visibility("hidden"), used)) void *app_orig[N + 1];')
w('static const char *const app_names[N + 1] = {')
for s in syms: w('  "%s",' % s)
w('  0 };')
w('void app_gl_bind(void *handle) { for (int i = 0; i < N; i++) app_tab[i] = dlsym(handle, app_names[i]); }')
for s in syms: w('extern void %s(void) __attribute__((weak_import));' % s)
w('#define STUB(name, i) \\')
w('  __attribute__((naked, used)) static void t_##name(void) { __asm__ volatile( \\')
w('    "adrp x16, _app_tab@PAGE\\n add x16, x16, _app_tab@PAGEOFF\\n ldr x16, [x16, #" #i "*8]\\n cbnz x16, 1f\\n" \\')
w('    "adrp x16, _app_orig@PAGE\\n add x16, x16, _app_orig@PAGEOFF\\n ldr x16, [x16, #" #i "*8]\\n 1: " BR); }')
for i, s in enumerate(syms): w('STUB(%s, %d)' % (s, i))
w('__attribute__((constructor(101))) static void app_orig_init(void) {')
for i, s in enumerate(syms): w('  app_orig[%d] = (void *)%s;' % (i, s))
w('}')
w('struct interpose { const void *replacement, *replacee; };')
w('__attribute__((used, section("__DATA,__interpose"))) static const struct interpose app_interpose[] = {')
for s in syms: w('  { (const void *)t_%s, (const void *)%s },' % (s, s))
w('};')
sys.stdout.write('\n'.join(o) + '\n')
